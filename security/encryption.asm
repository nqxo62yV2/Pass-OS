aes256_key_expand:
    push rbp
    mov rbp, rsp
    push rbx
    push r12
    push r13
    push r14

    mov r12, rdi
    mov r13, rsi

    mov rcx, 0
.copy_key:
    cmp rcx, 32
    jge .expand
    movzx rax, byte [r12 + rcx]
    mov byte [r13 + rcx], al
    inc rcx
    jmp .copy_key

.expand:
    mov rcx, 8
.expand_loop:
    cmp rcx, 60
    jge .done

    mov rbx, rcx
    and rbx, 3
    test rbx, rbx
    jnz .no_sched_core

    call _aes_key_schedule_core
    jmp .store

.no_sched_core:
    cmp rbx, 4
    jne .simple_xor
    call _aes_sub_word
    jmp .store

.simple_xor:
    mov rax, rcx
    sub rax, 1
    mov ebx, dword [r13 + rax * 4]
    sub rax, 7
    mov eax, dword [r13 + rax * 4]
    xor rax, rbx

.store:
    mov dword [r13 + rcx * 4], eax
    inc rcx
    jmp .expand_loop

.done:
    pop r14
    pop r13
    pop r12
    pop rbx
    mov rsp, rbp
    pop rbp
    ret

_aes_key_schedule_core:
    ret

_aes_sub_word:
    ret

aes256gcm_encrypt:
    push rbp
    mov rbp, rsp
    push rbx
    push r12
    push r13
    push r14
    push r15

    mov r12, rdi
    mov r13, rsi
    mov r14, rdx
    mov r15, rcx

    call hw_has_aes_ni
    test rax, rax
    jnz .use_hw
    call _aes256gcm_encrypt_soft
    jmp .done

.use_hw:
    call _aes256gcm_encrypt_hw

.done:
    xor rax, rax
    pop r15
    pop r14
    pop r13
    pop r12
    pop rbx
    mov rsp, rbp
    pop rbp
    ret

