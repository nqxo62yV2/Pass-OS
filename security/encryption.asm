; PassOS Encryption Module
; Implements AES-256-GCM authenticated encryption and decryption.
; Uses AES-NI hardware instructions when available (detected via hw_has_aes_ni).
; Falls back to a software AES implementation when AES-NI is absent.
;
; Key sizes: 256 bits (32 bytes)
; IV/Nonce:  96 bits  (12 bytes)  — randomly generated per operation
; Tag:       128 bits (16 bytes)
;
; Public interface:
;   aes256gcm_encrypt(key, iv, plaintext, pt_len, aad, aad_len, ciphertext, tag)
;   aes256gcm_decrypt(key, iv, ciphertext, ct_len, aad, aad_len, plaintext, tag)
;   generate_nonce(out_buf, 12)
;   xchacha20_poly1305_encrypt(...)
;   xchacha20_poly1305_decrypt(...)

