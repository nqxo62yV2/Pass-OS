generate_nonce:
    mov rsi, 12
    jmp secure_random_bytes

xchacha20_poly1305_encrypt:
    push rbp
    mov rbp, rsp
    call _xchacha20_encrypt
    call _poly1305_auth
    mov rsp, rbp
    pop rbp
    ret

xchacha20_poly1305_decrypt:
    push rbp
    mov rbp, rsp
    call _poly1305_verify
    jc .auth_failed
    call _xchacha20_encrypt
    xor rax, rax
    jmp .done

.auth_failed:
    mov rax, 1

.done:
    mov rsp, rbp
    pop rbp
    ret

